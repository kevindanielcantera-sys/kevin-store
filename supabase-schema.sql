-- Ejecutar una sola vez en Supabase > SQL Editor.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  category text not null check (category in ('Relojes', 'Gorras', 'Audífonos')),
  price integer not null check (price >= 0),
  old_price integer check (old_price is null or old_price >= 0),
  image_url text not null,
  badge text not null default '',
  description text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Tabla privada con los UUID permitidos para administrar el catálogo.
create table if not exists public.store_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.products enable row level security;
alter table public.store_admins enable row level security;
revoke all on public.products from anon, authenticated;
revoke all on public.store_admins from anon, authenticated;
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;

-- Comprueba el rol sin conceder al navegador lectura de store_admins.
create or replace function public.is_store_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.store_admins where user_id = (select auth.uid())
  );
$$;
revoke all on function public.is_store_admin() from public, anon;
grant execute on function public.is_store_admin() to authenticated;

drop policy if exists "Anyone can view active products" on public.products;
create policy "Anyone can view active products" on public.products
  for select using (active = true or (select public.is_store_admin()));
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products
  for all to authenticated
  using ((select public.is_store_admin()))
  with check ((select public.is_store_admin()));

grant usage, select on sequence public.products_id_seq to authenticated;

-- Fotos públicas para mostrarlas en la tienda; solo administradores pueden subirlas,
-- reemplazarlas o borrarlas. El límite de cada archivo es 5 MB.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 5242880,
  array['image/jpeg', 'image/png', 'image/webp', 'image/avif'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can view product photos" on storage.objects;
create policy "Public can view product photos" on storage.objects
  for select to anon, authenticated
  using (bucket_id = 'product-images');
drop policy if exists "Admins upload product photos" on storage.objects;
create policy "Admins upload product photos" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'product-images' and (select public.is_store_admin()));
drop policy if exists "Admins update product photos" on storage.objects;
create policy "Admins update product photos" on storage.objects
  for update to authenticated
  using (bucket_id = 'product-images' and (select public.is_store_admin()))
  with check (bucket_id = 'product-images' and (select public.is_store_admin()));
drop policy if exists "Admins delete product photos" on storage.objects;
create policy "Admins delete product photos" on storage.objects
  for delete to authenticated
  using (bucket_id = 'product-images' and (select public.is_store_admin()));

